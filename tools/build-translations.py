def unesc(s):
    return s.replace('\\"', '"').replace('\\\\', '\\')

def esc(s):
    return s.replace('\\', '\\\\').replace('"', '\\"')

pot = open(POT, encoding='utf-8').read()
missing = []
for locale, team in (('fr_CA', 'Français du Canada'), ('fr_FR', 'Français')):
    out = []
    entries = pot.split('\n\n')
    head = entries[0]
    head = head.replace('"Language-Team: Olivier Bigras <oli@olivierbigras.com>\\n"', f'"Language-Team: {team}\\n"\n"Language: {locale}\\n"')
    head = head.replace('"Plural-Forms: nplurals=INTEGER; plural=EXPRESSION;\\n"', '"Plural-Forms: nplurals=2; plural=(n > 1);\\n"')
    head = re.sub(r'"PO-Revision-Date: [^"]*"', lambda m: '"PO-Revision-Date: 2026-09-30 18:00-0400\\n"', head)
    out.append(head)
    for e in entries[1:]:
        m = re.search(r'^msgid "(.*)"$', e, re.M)
        if not m:
            out.append(e); continue
        key = unesc(m.group(1))
        c = re.search(r'^msgctxt "(.*)"$', e, re.M)
        tr = TX.get((unesc(c.group(1)), key)) if c else T.get(key)
        if tr is None:
            if locale == 'fr_CA': missing.append(key)
            tr = ''
        e = re.sub(r'^msgstr ""$', 'msgstr "' + esc(tr) + '"', e, count=1, flags=re.M)
        out.append(e)
    po = os.path.join(LANG_DIR, f'oli-abandoned-cart-recovery-{locale}.po')
    open(po, 'w', encoding='utf-8').write('\n\n'.join(out))
    subprocess.run(['msgfmt', '--check', '-o', po[:-3] + '.mo', po], check=True)
    print('OK', locale)
if missing:
    print('MANQUANTS :', missing); sys.exit(1)
